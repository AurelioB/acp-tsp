pub fn palette() -> Palette {
    let tokens = |values: &[(&str, &str)]| -> BTreeMap<String, String> {
        values
            .iter()
            .map(|(k, v)| ((*k).into(), (*v).into()))
            .collect()
    };
    Palette {
        sf: None,
        name: Some(PaletteNames {
            dark: Some("titanium".into()),
            light: Some("light".into()),
        }),
        dark: Some(tokens(DARK)),
        light: Some(tokens(LIGHT)),
    }
}
